"""Write ``docs/map/``: a map of Will It Run made from the code itself, for any LLM that has to change it.

Nothing here is written by a model. Every line is read from the files: the docstring of each module, its public classes
and functions, what imports what, the HTTP routes, the database tables, what the interface calls, which tests cover
what. So the map cannot say something the code does not, and it is rewritten by the git hook at every commit.

    python scripts/build_context.py            # write docs/map/
    python scripts/build_context.py --check    # exit 1 when docs/map/ is not what the code says (CI uses this)

It uses only the standard library, so it runs with any Python 3.11+, with or without the project's virtual environment.
It leaves out line numbers on purpose: they change at every edit and a stale one is worse than none. For lines, symbols
and callers use ``codegraph explore`` (it reads the disk live).
"""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "backend" / "src" / "agentfit"
TESTS = ROOT / "backend" / "tests"
FRONT = ROOT / "desktop" / "src"
TAURI = ROOT / "desktop" / "src-tauri" / "src"
DOCS = ROOT / "docs"
SCRIPTS = ROOT / "scripts"
OUT = DOCS / "map"

#: A card longer than this is split by sub-package: it is read by models with a small window.
CARD_LIMIT = 15_000
HEADER = "<!-- Generated by scripts/build_context.py from the code. Do not edit: run it again. -->\n"
HTTP_METHODS = ("get", "post", "put", "delete", "patch")
SKIP_PARTS = {"__pycache__", "node_modules", ".venv", "dist", "build", "target"}


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def tokens(text: str) -> int:
    return round(len(text) / 4)


def sentence(text: str | None, limit: int = 170) -> str:
    """The first sentence of a docstring, on one line."""
    if not text:
        return ""
    flat = " ".join(text.strip().split("\n\n", 1)[0].split())
    cut = re.search(r"(?<=[a-z0-9\)`\"'])\.(?:\s|$)", flat)
    if cut:
        flat = flat[: cut.start() + 1]
    return flat if len(flat) <= limit else flat[: limit - 1].rstrip() + "…"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _tracked() -> frozenset[str] | None:
    """The paths git has (tracked or staged), or None when there is no git to ask.

    The map describes the repository, so a scratch file nobody added is not in it: that is what keeps the map the same on every
    machine and lets CI check it.
    """
    try:
        done = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--cached", "-z"], capture_output=True, timeout=30, check=True)
    except (OSError, subprocess.SubprocessError):
        return None
    return frozenset(name for name in done.stdout.decode("utf-8", "replace").split("\0") if name) or None


TRACKED = _tracked()


def listing(base: Path, pattern: str, *, deep: bool = True) -> list[Path]:
    """The repository's files under ``base`` that match ``pattern``, in a fixed order."""
    found = base.rglob(pattern) if deep else base.glob(pattern)
    return sorted(p for p in found if not SKIP_PARTS & set(p.relative_to(ROOT).parts) and (TRACKED is None or rel(p) in TRACKED))


# -- Python -----------------------------------------------------------------------------------------------


@dataclass
class PyModule:
    path: Path
    module: str
    package: str
    loc: int
    doc: str
    classes: list[tuple[str, str, list[str]]] = field(default_factory=list)  # name, first doc sentence, public methods
    functions: list[tuple[str, str]] = field(default_factory=list)
    imports: set[str] = field(default_factory=set)  # internal modules this one imports
    tests: set[str] = field(default_factory=set)


def py_files(base: Path) -> list[Path]:
    return listing(base, "*.py")


def module_name(path: Path) -> str:
    parts = list(path.relative_to(SRC.parent).with_suffix("").parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def package_of(module: str) -> str:
    parts = module.split(".")
    return parts[1] if len(parts) > 2 else "core"


#: ``package -> {name: module}`` for what a package's ``__init__`` re-exports: importing the name is using that module.
REEXPORTS: dict[str, dict[str, str]] = {}


def resolve_import(node: ast.ImportFrom | ast.Import, current: str, is_package: bool, known: set[str]) -> set[str]:
    found: set[str] = set()
    if isinstance(node, ast.Import):
        names = [alias.name for alias in node.names]
    else:
        base = node.module or ""
        if node.level:
            parts = current.split(".")
            parts = parts if is_package else parts[:-1]
            parts = parts[: len(parts) - (node.level - 1)] if node.level > 1 else parts
            base = ".".join([*parts, *([base] if base else [])])
        names = [base] + [f"{base}.{alias.name}" for alias in node.names]
    for name in names:
        if name.startswith("agentfit") and name in known:
            found.add(name)
    if isinstance(node, ast.ImportFrom):
        for alias in node.names:
            target = REEXPORTS.get(names[0], {}).get(alias.name)
            if target:
                found.add(target)
    return found


def parse_python(path: Path, known: set[str]) -> PyModule:
    text = path.read_text(encoding="utf-8-sig")
    name = module_name(path)
    module = PyModule(path=path, module=name, package=package_of(name), loc=text.count("\n") + 1, doc="")
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return module
    module.doc = sentence(ast.get_docstring(tree))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            methods = [n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")]
            module.classes.append((node.name, sentence(ast.get_docstring(node), 110), methods))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            module.functions.append((node.name, sentence(ast.get_docstring(node), 110)))
    is_package = path.name == "__init__.py"
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            module.imports |= resolve_import(node, name, is_package, known)
    module.imports.discard(name)
    return module


def load_python() -> dict[str, PyModule]:
    files = py_files(SRC)
    known = {module_name(p) for p in files}
    REEXPORTS.clear()
    for path in files:
        if path.name != "__init__.py":
            continue
        package = module_name(path)
        for node in ast.parse(path.read_text(encoding="utf-8-sig")).body:
            if not (isinstance(node, ast.ImportFrom) and node.module):
                continue
            target = f"{package}.{node.module}" if node.level == 1 else node.module
            if node.level <= 1 and target in known:
                for alias in node.names:
                    REEXPORTS.setdefault(package, {})[alias.asname or alias.name] = target
    return {m.module: m for m in (parse_python(p, known) for p in files)}


@dataclass
class TestFile:
    name: str
    doc: str
    count: int
    covers: set[str]


def load_tests(modules: dict[str, PyModule]) -> list[TestFile]:
    known = set(modules)
    tests = []
    for path in listing(TESTS, "test_*.py", deep=False):
        text = path.read_text(encoding="utf-8-sig")
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        covers: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                covers |= resolve_import(node, "tests." + path.stem, False, known)
        count = len(re.findall(r"^\s*(?:async )?def test_", text, re.M))
        tests.append(TestFile(path.name, sentence(ast.get_docstring(tree), 150), count, covers))
    for test in tests:
        for name in test.covers:
            modules[name].tests.add(test.name)
    return tests


# -- routes and tables -----------------------------------------------------------------------------------


@dataclass
class Route:
    method: str
    path: str
    handler: str
    file: str
    doc: str


def load_routes() -> list[Route]:
    routes: list[Route] = []
    for path in listing(SRC / "api", "*.py", deep=False):
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if not (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute) and isinstance(deco.func.value, ast.Name)):
                    continue
                if deco.func.value.id != "app" or deco.func.attr not in HTTP_METHODS:
                    continue
                if deco.args and isinstance(deco.args[0], ast.Constant) and isinstance(deco.args[0].value, str):
                    routes.append(Route(deco.func.attr.upper(), deco.args[0].value, node.name, path.name, sentence(ast.get_docstring(node), 120)))
    return sorted(routes, key=lambda r: (r.path, r.method))


def norm_path(path: str) -> str:
    """A route, or a path written in the UI, with every parameter spelled ``{}``.

    In the UI a ``${...}`` inside the path is an id; one at the end is a query string built by a helper, and is dropped.
    """
    out, i = "", 0
    while i < len(path):
        if path.startswith("${", i):
            depth, j = 0, i + 1
            while j < len(path):
                depth += path[j] == "{"
                depth -= path[j] == "}"
                j += 1
                if depth == 0:
                    break
            if out.endswith("/"):
                out += "{}"
            elif path[j:] and not path[j:].startswith("/"):
                break
            i = j
        else:
            out += path[i]
            i += 1
    out = re.sub(r"\{[^}]*\}", "{}", out.split("?")[0])
    return out.rstrip("/") or "/"


def ui_api_paths(text: str) -> set[str]:
    """The ``/api/...`` paths a source file writes in a string, with ids as ``{}`` (comments and prose are not strings)."""
    found: set[str] = set()
    for match in re.finditer(r"(?<=[`\"'}])/api/", text):
        j = match.start()
        while j < len(text):
            if text.startswith("${", j):
                depth, k = 0, j + 1
                while k < len(text):
                    depth += text[k] == "{"
                    depth -= text[k] == "}"
                    k += 1
                    if depth == 0:
                        break
                j = k
                continue
            if text[j] in "`\"'\\ \t\n)>,;":
                break
            j += 1
        found.add(norm_path(text[match.start() : j]))
    return found


@dataclass
class Table:
    name: str
    migration: str
    columns: list[str]
    note: str


def load_tables() -> list[Table]:
    tables: list[Table] = []
    for path in listing(SRC / "migrations", "*.sql", deep=False):
        text = path.read_text(encoding="utf-8-sig")
        for match in re.finditer(r"((?:--[^\n]*\n)*)\s*CREATE (?:VIRTUAL )?TABLE (?:IF NOT EXISTS )?(\w+)\s*(?:\(|USING)(.*?)\n\);?", text, re.S | re.I):
            note = " ".join(line.lstrip("- ").strip() for line in match.group(1).splitlines()).strip()
            columns = []
            depth = 0
            current = ""
            for char in match.group(3):
                if char == "(":
                    depth += 1
                elif char == ")":
                    depth -= 1
                if char == "," and depth == 0:
                    columns.append(current.strip())
                    current = ""
                else:
                    current += char
            columns.append(current.strip())
            cleaned = []
            for column in columns:
                column = re.sub(r"--[^\n]*", "", column).strip()
                if not column or re.match(r"(PRIMARY KEY|FOREIGN KEY|UNIQUE|CHECK|CONSTRAINT)\b", column, re.I):
                    continue
                cleaned.append(" ".join(column.split()).split(" DEFAULT")[0].split(" NOT NULL")[0].split(" REFERENCES")[0])
            tables.append(Table(match.group(2), path.name, cleaned, sentence(note, 160)))
    return tables


# -- the interface ------------------------------------------------------------------------------------------


@dataclass
class TsFile:
    path: Path
    loc: int
    exports: list[str]
    imports: list[str]
    api: set[str]
    events: set[str]


def load_frontend() -> list[TsFile]:
    files = []
    for path in listing(FRONT, "*.ts*"):
        if "locales" in path.parts or path.name.endswith((".test.ts", ".d.ts")):
            continue
        text = path.read_text(encoding="utf-8-sig")
        exports = re.findall(r"^export (?:default )?(?:async )?(?:function|const|class|interface|type|enum) (\w+)", text, re.M)
        imports = [Path(m).name for m in re.findall(r"from \"(\.{1,2}/[^\"]+)\"", text)]
        api = ui_api_paths(text)
        events = set(re.findall(r"useBus\(\s*\"([^\"]+)\"", text))
        files.append(TsFile(path, text.count("\n") + 1, exports, imports, api, events))
    return files


# -- writing --------------------------------------------------------------------------------------------------


def purpose_of(package: str, modules: dict[str, PyModule], architecture: dict[str, str]) -> str:
    if package == "core":
        return "Entry points and shared plumbing: AppServices wiring (app.py), CLI, config, db, events, paths, downloads, chat, runtime, i18n."
    init = modules.get(f"agentfit.{package}")
    text = init.doc if init and init.doc else architecture.get(package, "")
    return text[:1].upper() + text[1:]


def architecture_lines() -> dict[str, str]:
    path = DOCS / "ARCHITECTURE.md"
    if not path.exists():
        return {}
    out = {}
    for match in re.finditer(r"^\s*\+-- (\w+)/?(?:\.py)?\s+(.+)$", path.read_text(encoding="utf-8-sig"), re.M):
        out[match.group(1)] = match.group(2).strip()
    return out


def symbol_text(module: PyModule, limit: int = 9) -> str:
    names = [f"**{name}**" for name, _, _ in module.classes] + [f"{name}()" for name, _ in module.functions]
    shown = names[:limit]
    more = f" +{len(names) - limit} more" if len(names) > limit else ""
    return ", ".join(shown) + more


def package_card(package: str, mods: list[PyModule], graph: dict[str, set[str]], used_by: dict[str, set[str]], tests_of: dict[str, set[str]],
                 purpose: str, routes_in: dict[str, int], sub: str | None = None) -> str:
    title = f"{package}/{sub}" if sub else package
    lines = [HEADER, f"# Backend package `{title}`\n"]
    if purpose and not sub:
        lines.append(f"{purpose}\n")
    if not sub:
        uses = ", ".join(f"`{p}`" for p in sorted(graph.get(package, ()))) or "nothing else of the project"
        used = ", ".join(f"`{p}`" for p in sorted(used_by.get(package, ()))) or "nobody (an entry point)"
        tests = ", ".join(f"`{t}`" for t in sorted(tests_of.get(package, ()))) or "none imports it directly"
        lines.append(f"- Depends on: {uses}\n- Used by: {used}\n- Tests that import it: {tests}")
        if routes_in.get(package):
            lines.append(f"- HTTP routes: see `api.md` (`api/{package}_routes.py`)")
        lines.append("")
    lines += ["| File | Lines | What it is | Public symbols | Tests |", "|---|---:|---|---|---|"]
    for m in sorted(mods, key=lambda x: x.path):
        name = m.path.relative_to(SRC).as_posix()
        tests = ", ".join(sorted(m.tests)[:3]) + (f" +{len(m.tests) - 3}" if len(m.tests) > 3 else "")
        lines.append(f"| `{name}` | {m.loc} | {cell(m.doc)} | {cell(symbol_text(m))} | {cell(tests)} |")
    return "\n".join(lines) + "\n"


def build_files() -> dict[str, str]:
    modules = load_python()
    tests = load_tests(modules)
    routes = load_routes()
    tables = load_tables()
    front = load_frontend()
    architecture = architecture_lines()
    out: dict[str, str] = {}

    packages: dict[str, list[PyModule]] = defaultdict(list)
    for m in modules.values():
        packages[m.package].append(m)
    graph: dict[str, set[str]] = defaultdict(set)
    used_by: dict[str, set[str]] = defaultdict(set)
    for m in modules.values():
        for target in m.imports:
            other = package_of(target)
            if other != m.package:
                graph[m.package].add(other)
                used_by[other].add(m.package)
    tests_of: dict[str, set[str]] = defaultdict(set)
    for t in tests:
        for name in t.covers:
            tests_of[package_of(name)].add(t.name)
    routes_in = defaultdict(int)
    for r in routes:
        match = re.match(r"(\w+)_routes\.py", r.file)
        if match:
            routes_in[match.group(1)] += 1

    # one card per package; a card that is too long is split by sub-package
    for package, mods in sorted(packages.items()):
        purpose = purpose_of(package, modules, architecture)
        card = package_card(package, mods, graph, used_by, tests_of, purpose, routes_in)
        if len(card) <= CARD_LIMIT:
            out[f"{package}.md"] = card
            continue
        subs: dict[str, list[PyModule]] = defaultdict(list)
        for m in mods:
            parts = m.path.relative_to(SRC).parts
            subs[parts[1] if len(parts) > 2 else ""].append(m)
        top = subs.pop("", [])
        index = [f"- `{package}.md` (this file): the files directly in `{package}/`"] + [
            f"- `{package}-{name}.md`: `{package}/{name}/` ({len(items)} files)" for name, items in sorted(subs.items())
        ]
        head = package_card(package, top, graph, used_by, tests_of, purpose, routes_in)
        out[f"{package}.md"] = head + "\nSub-packages have their own cards:\n\n" + "\n".join(index) + "\n"
        for name, items in sorted(subs.items()):
            out[f"{package}-{name}.md"] = package_card(package, items, graph, used_by, tests_of, "", routes_in, sub=name)

    # HTTP routes
    lines = [HEADER, "# HTTP routes\n", f"{len(routes)} routes, all under the token guard of `api/server.py`. Handlers are plain functions: grep the name.\n"]
    by_file: dict[str, list[Route]] = defaultdict(list)
    for r in routes:
        by_file[r.file].append(r)
    for file, items in sorted(by_file.items()):
        lines += [f"## `api/{file}` ({len(items)})\n", "| Method | Path | Handler | What it does |", "|---|---|---|---|"]
        lines += [f"| {r.method} | `{r.path}` | `{r.handler}` | {cell(r.doc)} |" for r in items]
        lines.append("")
    out["api.md"] = "\n".join(lines)

    # database
    lines = [HEADER, "# Database (SQLite, numbered migrations in `backend/src/agentfit/migrations/`)\n",
             "Never edit a migration that was applied: add the next number. Columns as written in the SQL (defaults left out).\n"]
    for t in tables:
        lines.append(f"- **{t.name}** (`{t.migration}`){': ' + t.note if t.note else ''}\n  columns: {', '.join(t.columns)}")
    out["db.md"] = "\n".join(lines) + "\n"

    # interface
    backend_paths = {norm_path(r.path) for r in routes}
    called: set[str] = set()
    lines = [HEADER, "# Interface (`desktop/src`, React + TypeScript) and shell (`desktop/src-tauri`)\n",
             "The UI talks to the core only over HTTP (`desktop/src/lib/api.ts`) and one event stream. Texts are English keys translated "
             "from `desktop/src/locales/it.txt` (never edit `it.ts`).\n"]
    for group in ("pages", "components", "lib"):
        items = [f for f in front if f.path.relative_to(FRONT).parts[0] == group]
        if not items:
            continue
        lines += [f"## `{group}/`\n", "| File | Lines | Exports | Calls the core | Bus events |", "|---|---:|---|---|---|"]
        for f in items:
            called |= f.api
            api = sorted(f.api)
            shown = ", ".join(f"`{p}`" for p in api[:6]) + (f" +{len(api) - 6}" if len(api) > 6 else "")
            exports = ", ".join(f.exports[:7]) + (f" +{len(f.exports) - 7}" if len(f.exports) > 7 else "")
            lines.append(f"| `{f.path.relative_to(FRONT).as_posix()}` | {f.loc} | {cell(exports)} | {cell(shown)} | {cell(', '.join(sorted(f.events)))} |")
        lines.append("")
    unmatched = sorted(p for p in called if p not in backend_paths)
    lines.append("## Consistency with the core\n")
    lines.append("UI paths with no route of that shape: " + (", ".join(f"`{p}`" for p in unmatched[:25]) or "none") + "\n")
    never = sorted({r.path for r in routes if norm_path(r.path) not in called})
    shown = ", ".join(f"`{p}`" for p in never[:30]) + (" …" if len(never) > 30 else "")
    lines.append(f"Routes the UI never calls ({len(never)}; they serve the CLI, the Tauri shell or tests): {shown or 'none'}\n")
    rust = TAURI / "lib.rs"
    if rust.exists():
        names = re.findall(r"^\s*(?:pub )?(?:async )?fn (\w+)", rust.read_text(encoding="utf-8-sig"), re.M)
        lines.append(f"## Shell (`desktop/src-tauri/src/lib.rs`, {rust.read_text(encoding='utf-8').count(chr(10)) + 1} lines)\n")
        lines.append("Starts and stops the Python core, the window, notifications and links. Functions: " + ", ".join(f"`{n}`" for n in names) + "\n")
    out["frontend.md"] = "\n".join(lines)

    # tests
    lines = [HEADER, "# Tests (`backend/tests`, pytest; `desktop/src/**/*.test.ts`, vitest)\n",
             "They never touch LM Studio, the network or your data (`conftest.py` points `AGENTFIT_HOME` at a temp folder). Run from `backend/`: "
             "`.venv\\Scripts\\python.exe -m pytest`.\n", "| File | Tests | What it checks | Packages it imports |", "|---|---:|---|---|"]
    for t in tests:
        pkgs = ", ".join(sorted({package_of(n) for n in t.covers}))
        lines.append(f"| `{t.name}` | {t.count} | {cell(t.doc)} | {pkgs} |")
    ts_tests = listing(FRONT, "*.test.ts")
    lines.append("\nFront-end tests: " + ", ".join(f"`{p.relative_to(FRONT).as_posix()}`" for p in ts_tests) + "\n")
    out["tests.md"] = "\n".join(lines)

    # the index
    total_py = sum(m.loc for m in modules.values())
    total_ts = sum(f.loc for f in front)
    lines = [HEADER, "# Will It Run: map of the code\n",
             "Read this first, then the card of the package you will touch. For symbols, lines and callers use `codegraph explore \"<question>\"`; "
             "for what happened before, `willitrun memory search`. Rules and commands are in `AGENTS.md`.\n",
             f"{len(modules)} Python files ({total_py:,} lines) · {sum(len(m.classes) + len(m.functions) for m in modules.values())} public symbols · "
             f"{len(routes)} HTTP routes · {len(tables)} tables · {len(tests)} test files ({sum(t.count for t in tests)} tests) · "
             f"{len(front)} UI files ({total_ts:,} lines).\n", "## Backend packages (`backend/src/agentfit/<name>/`)\n",
             "| Package | What it is | Files | Lines | Depends on | Card |", "|---|---|---:|---:|---|---|"]
    for package, mods in sorted(packages.items()):
        purpose = purpose_of(package, modules, architecture)
        lines.append(f"| `{package}` | {cell(purpose)} | {len(mods)} | {sum(m.loc for m in mods):,} | {cell(', '.join(sorted(graph.get(package, ()))))} | `{package}.md` |")
    lines += ["", "## Other cards\n", "- `api.md`: every HTTP route · `db.md`: every table · `frontend.md`: every UI file, what it calls, the Rust shell · `tests.md`: every test file\n",
              "## Documents (`docs/`)\n", "| File | Title | About |", "|---|---|---|"]
    for path in listing(DOCS, "*.md", deep=False):
        text = path.read_text(encoding="utf-8-sig")
        title = (re.search(r"^# (.+)$", text, re.M) or [None, path.stem])[1]
        text = re.sub(r"```.*?```", "", text, flags=re.S)
        blocks = [b.strip() for b in re.sub(r"^#.*$", "", text, flags=re.M).split("\n\n") if b.strip()]
        body = next((b for b in blocks if not b.startswith(("|", "-", "*", "<", ">"))), "")
        lines.append(f"| `{path.name}` | {cell(title)} | {cell(sentence(body, 150))} |")
    lines += ["", "## Scripts (`scripts/`)\n"]
    for path in listing(SCRIPTS, "*.py", deep=False):
        if path.name.startswith("_"):
            continue
        try:
            doc = sentence(ast.get_docstring(ast.parse(path.read_text(encoding="utf-8-sig"))), 150)
        except SyntaxError:
            doc = ""
        lines.append(f"- `scripts/{path.name}`: {doc}")
    out["INDEX.md"] = "\n".join(lines) + "\n"
    return out


def normalise(text: str) -> str:
    return text.replace("\r\n", "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Write docs/map/ from the code, or check that it is up to date.")
    parser.add_argument("--check", action="store_true", help="Change nothing: exit 1 if docs/map/ differs from the code.")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()
    files = build_files()
    if args.check:
        stale = []
        for name, text in files.items():
            path = OUT / name
            if not path.exists() or normalise(path.read_text(encoding="utf-8-sig")) != text:
                stale.append(name)
        stale += [p.name for p in OUT.glob("*.md") if p.name not in files] if OUT.exists() else []
        if stale:
            print("docs/map/ is out of date: " + ", ".join(sorted(stale)))
            print("Run: python scripts/build_context.py   (the git pre-commit hook does it for you)")
            return 1
        print(f"docs/map/ is up to date ({len(files)} files).")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        path = OUT / name
        if not path.exists() or normalise(path.read_text(encoding="utf-8-sig")) != text:
            path.write_text(text, encoding="utf-8", newline="\n")
    if not args.quiet:
        for name, text in sorted(files.items()):
            print(f"{name:24} {len(text):>7,} chars  ~{tokens(text):>5,} tokens")
    return 0


if __name__ == "__main__":
    sys.exit(main())
