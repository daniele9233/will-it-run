"""Check and build the Italian UI catalog.

The interface uses the English text as the translation key: ``t("Explore Models")``.
This script collects every key from ``desktop/src``, compares it with the translations
in ``desktop/src/locales/it.txt`` (one ``English ||| Italiano`` pair per line) and writes
``desktop/src/locales/it.ts``. It fails when a key has no translation or a translation
loses a ``{placeholder}``, so a missing string is caught at build time, not on screen.

    python scripts/build_locale.py            # check and rebuild it.ts
    python scripts/build_locale.py --missing  # only list untranslated keys
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "desktop" / "src"
PAIRS = SRC / "locales" / "it.txt"
OUT = SRC / "locales" / "it.ts"
SEPARATOR = " ||| "

_DOUBLE = r'"((?:[^"\\]|\\.)*)"'
_SINGLE = r"'((?:[^'\\]|\\.)*)'"
_CALL = re.compile(r"\bt\(\s*(?:" + _DOUBLE + "|" + _SINGLE + ")")
_PLACEHOLDER = re.compile(r"\{(\w+)\}")


def source_keys() -> dict[str, str]:
    keys: dict[str, str] = {}
    for path in sorted([*SRC.rglob("*.tsx"), *SRC.rglob("*.ts")]):
        if path.name.endswith(".test.ts") or "locales" in path.parts:
            continue
        for match in _CALL.finditer(path.read_text(encoding="utf-8")):
            if match.group(1) is not None:
                key = json.loads('"' + match.group(1) + '"')
            else:
                key = json.loads('"' + match.group(2).replace("\\'", "'").replace('"', '\\"') + '"')
            keys.setdefault(key, path.name)
    return keys


def translations() -> dict[str, str]:
    pairs: dict[str, str] = {}
    for number, line in enumerate(PAIRS.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        if SEPARATOR not in line:
            raise SystemExit(f"{PAIRS.name}:{number}: no '{SEPARATOR.strip()}' separator")
        key, value = line.split(SEPARATOR, 1)
        pairs[key] = value.rstrip()
    return pairs


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    keys = source_keys()
    pairs = translations()
    missing = [k for k in keys if k not in pairs]
    unused = [k for k in pairs if k not in keys]
    broken = [
        k for k, v in pairs.items()
        if k in keys and sorted(_PLACEHOLDER.findall(k)) != sorted(_PLACEHOLDER.findall(v))
    ]
    for key in missing:
        print(f"MISSING  [{keys[key]}] {key}")
    if "--missing" in sys.argv:
        return 1 if missing else 0
    for key in broken:
        print(f"PLACEHOLDER MISMATCH  {key}  ->  {pairs[key]}")
    for key in unused:
        print(f"unused   {key}")
    if missing or broken:
        print(f"{len(missing)} missing, {len(broken)} with wrong placeholders: it.ts not written")
        return 1
    body = "".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(pairs[k], ensure_ascii=False)},\n" for k in sorted(keys, key=str.lower))
    OUT.write_text(
        "// Italian catalog. Generated by scripts/build_locale.py from it.txt: edit that file, not this one.\n"
        "// Keys are the English source strings used with t().\n"
        f"export const it: Record<string, string> = {{\n{body}}};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(keys)} strings, {len(unused)} unused translations; wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
